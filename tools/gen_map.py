def _cut(text: str, width: int = GIST) -> str:
    text = " ".join(text.split())
    if len(text) <= width:
        return text
    return text[:width - 1].rstrip() + "…"


def _tier1_line(entry: Entry) -> str:
    """One symbol, one line, tag FIRST.

    Tag first because this line's whole job is to be the result of
    `grep -rn "#TAG:GameEntity"`: the tag is the query, so it reads as the
    query's answer, and the address that follows is what the reader wanted.
    The symbol's own name is not repeated -- for everything but a collided
    name the tag IS the name, and 470 repetitions of it is a kilobyte the
    file-that-is-always-read cannot justify. Neither is the directory: the
    module line directly above carries the full path, the tier-2 file carries
    it again, and a grep for the tag hits BOTH files, so the basename here is
    a disambiguator rather than an address.
    """
    kind = "class" if entry.kind == "class" else "def"
    head = "%s%s %s %s:%d" % (TAG, entry.tag, kind,
                              os.path.basename(entry.relpath), entry.lineno)
    gist = _cut(entry.doc, 46)
    return head + ("  · " + gist if gist else "")


def render_index(modules: list[Module] | None = None) -> str:
    modules = load() if modules is None else modules
    counts = {
        "modules": len(modules),
        "classes": sum(len(m.classes) for m in modules),
        "functions": sum(len([e for e in m.functions if e.public]) for m in modules),
        "methods": sum(len([e for e in m.entries if e.kind == "method"]) for m in modules),
        "constants": sum(len(m.constants) for m in modules),
    }
    out = [BANNER.rstrip("\n"), "",
           "# Map — tier 1, the gist", "",
           "**Read this whole file, and read it before you read any source.** "
           "It is the index: what exists, and where. It is deliberately not "
           "enough to write code against.", "",
           "Three ways down from here, cheapest first:", "",
           "| you want | do this | costs |", "|---|---|---|",
           "| one signature | `grep -rn \"%sGameEntity\"` — returns the "
           "definition line AND every document that cites it | nothing |" % TAG,
           "| to touch one module | open its tier-2 file: `docs/map/` + the "
           "module path with `/` and `.py` replaced by `.` + `.md`, so "
           "`scripts/core/depth.py` is [`docs/map/scripts.core.depth.md`]"
           "(map/scripts.core.depth.md) | ~1 page |",
           "| all of it | do not. Loading every tier-2 file costs more than "
           "reading the source, which is the exact failure two tiers exist to "
           "prevent | ~%dk |" % (sum(len(render_module(m)) for m in modules)
                                 // 4000), "",
           "Generated by `tools/gen_map.py` from the AST, so no line here can "
           "name something that does not exist, and no line here has to be "
           "maintained. Regenerate after any structural edit:", "",
           "    " + REGENERATE, "",
           "Covers `%s`. It does **not** cover `tools/` — a check module is "
           "read whole or not at all, and the roster is generated into "
           "[`CHECKS.md`](CHECKS.md)." % "`, `".join(ROOTS), "",
           "%d modules · %d classes · %d public functions · %d methods · "
           "%d constants. Methods and constants are **tier 2 only** — they "
           "still carry tags, and the tag is what you grep."
           % (counts["modules"], counts["classes"], counts["functions"],
              counts["methods"], counts["constants"]), ""]

    package = None
    for module in modules:
        if module.package != package:
            if package is not None:
                out += ["```", ""]
            package = module.package
            out += ["## `%s`" % package, "", "```"]
        gist = _cut(module.doc, 74)
        out.append("%s%s  %d line%s%s"
                   % (TAG, module.tag, module.lines,
                      "" if module.lines == 1 else "s",
                      "  · " + gist if gist else ""))
        rows = module.classes + [e for e in module.functions if e.public]
        for entry in sorted(rows, key=lambda e: e.lineno):
            out.append("  " + _tier1_line(entry))
    out += ["```", ""]
    return "\n".join(out).rstrip("\n") + "\n"


# ---------------------------------------------------------------------------
# Tier 2 -- docs/map/<dotted>.md
# ---------------------------------------------------------------------------

def tier2_rel(module: Module) -> str:
    return "%s/%s.md" % (TIER2_DIR, module.dotted)


def _render_callable(entry: Entry) -> list[str]:
    decorated = "".join("@%s " % d for d in entry.decorators)
    sig = "%s%s(%s)%s" % (decorated, entry.name, entry.signature,
                          " -> %s" % entry.returns if entry.returns else "")
    line = "- `%s:%d` `%s` %s%s" % (entry.relpath, entry.lineno, sig,
                                    TAG, entry.tag)
    out = [line]
    if entry.doc:
        out.append("  - %s" % _cut(entry.doc, 110))
    return out


def render_module(module: Module) -> str:
    out = [BANNER.rstrip("\n"), "",
           "# `%s` — tier 2 %s%s" % (module.relpath, TAG, module.tag), ""]
    if module.doc:
        out += ["> %s" % _cut(module.doc, 160), ""]
    out += ["`%s` · %d lines · tier 1: [`../MAP.md`](../MAP.md)"
            % (module.dotted, module.lines), ""]
    if module.imports:
        out += ["**First-party imports.** `scripts/` may never import "
                "`editor/` — this line is where that is auditable.", "",
                "    " + " ".join(module.imports), ""]

    if module.constants:
        out += ["## Module constants", ""]
        for entry in module.constants:
            out.append("- `%s:%d` `%s` %s%s"
                       % (entry.relpath, entry.lineno, entry.name, TAG, entry.tag))
        out.append("")

    functions = module.functions
    if functions:
        out += ["## Functions", ""]
        for entry in sorted(functions, key=lambda e: e.lineno):
            out += _render_callable(entry)
        out.append("")

    classes = module.classes
    if classes:
        out += ["## Classes", ""]
        for entry in sorted(classes, key=lambda e: e.lineno):
            bases = "(%s)" % ", ".join(entry.bases) if entry.bases else ""
            decorated = "".join("@%s " % d for d in entry.decorators)
            out += ["### `%sclass %s%s` %s%s"
                    % (decorated, entry.name, bases, TAG, entry.tag), "",
                    "`%s:%d`–`%d`" % (entry.relpath, entry.lineno,
                                      entry.end_lineno), ""]
            if entry.doc:
                out += ["> %s" % _cut(entry.doc, 160), ""]
            methods = module.methods_of(entry.name)
            if methods:
                for method in sorted(methods, key=lambda e: e.lineno):
                    out += _render_callable(method)
            else:
                out.append("- (no methods)")
            out.append("")

    if not (module.constants or functions or classes):
        out += ["This module defines no class, function or public constant.", ""]
    return "\n".join(out).rstrip("\n") + "\n"


