"""Generate the two-tier code map, and the #TAG index every doc addresses by.

    .venv/Scripts/python.exe tools/gen_map.py            # verify, exit 1 on drift
    .venv/Scripts/python.exe tools/gen_map.py --write    # regenerate
    .venv/Scripts/python.exe tools/gen_map.py --tags     # print the tag index

WHY THIS IS GENERATED AND NOT WRITTEN
-------------------------------------
A hand-written index over 130 modules is dead in a week. `docs/history/ORPHANS.md` is
what that looks like after one, and the nine documentation sites that stated
the opposite of a shipped wire in one review pass are what it looks like after
three. The strongest pattern already in this tree is `describe_all` ->
`docs/BEHAVIORS.md`: a document that cannot describe a behavior that does not
exist. This applies the same rule to the shape of the code itself. Nothing
below is typed by a human, so nothing below can be wrong about what exists.

WHY A #TAG AND NOT A LINE NUMBER
--------------------------------
Measured, and the reason this file exists: `CLAUDE.md`'s anchor table used to
pin quoted source lines by `FILE:LINE`. A five-line docstring edit above one of
them turned `check_docs` red --

    game_entity.py:236 no longer contains 'if field is None or bit is None'
    -- it moved to line 241

The anchor was not wrong. The document was not stale. Nothing about the
documented fact had changed. A line number is an address that every edit above
it invalidates; a `#TAG:` is an address that survives one. So a document says
`#TAG:GameEntity.allowed_move` and a checker re-derives the line every run.

THE TWO TIERS, AND WHY THERE ARE TWO
------------------------------------
`docs/MAP.md`          TIER 1. One line per module, class and public function,
                       with `file:line` and a tag. Read it FIRST, always. It is
                       a gist: enough to know what exists and where, never
                       enough to write code against.
`docs/map/<mod>.md`    TIER 2. One file per module: full signatures with args
                       and defaults, return annotations where declared, the
                       first docstring line, module constants and every method.
                       Loaded ONLY when that module is being touched.

Loading every tier-2 file at once costs more than reading the source and
defeats the entire point. `docs/MAP.md` says so in its own preamble, and
`tools/check_docs.py` measures both files' sizes so the claim stays true.

WHAT IS MAPPED
--------------
`ROOTS` below: the code a game or an editor feature is written against.
`tools/` is deliberately NOT mapped -- a check module is read whole or not at
all, and its roster is already generated into `docs/CHECKS.md`. That exclusion
is a constant here rather than a habit, and `check_docs` asserts the mapped
roots are covered in BOTH directions: no module without a map, no map without
a module.
"""
from __future__ import annotations

import _bootstrap  # noqa: F401  (must precede engine imports)

import argparse
import ast
import os
import re
import sys
from dataclasses import dataclass, field

ROOT = _bootstrap.REPO_ROOT

ROOTS = ("config", "demos", "editor", "main.py", "scripts")
"""What the map covers. See the module docstring for what it does not."""

INDEX_REL = "docs/MAP.md"
TIER2_DIR = "docs/map"

REGENERATE = ".venv/Scripts/python.exe tools/gen_map.py --write"

BANNER = (
    "<!-- pyoneer-doc: L1 -->\n"
    "<!-- GENERATED by tools/gen_map.py. Do not edit. "
    "Regenerate: %s -->\n" % REGENERATE)

TAG = "#TAG:"

TAG_VALUE = re.compile(r"[A-Za-z0-9_](?:[A-Za-z0-9_./]*[A-Za-z0-9_])?")
"""What a tag value may contain: names, dots, slashes; never a trailing dot.

One expression for all four shapes -- `ClassName`, `function_name`,
`Owner.method`, `path/to/module.py` -- because a grammar that tried to tell a
`topic_slug` from a `function_name` would be a fifth rule nobody remembers,
and the real proof that a tag is valid is that it RESOLVES, which
`tools/check_docs.py` asserts against this file's index. The trailing-character
clause is what stops `see #TAG:GameEntity.` from claiming the tag
`GameEntity.`, which resolves nowhere and would fail for a typographical
reason.
"""

# The tag scanner must not match its own documentation. `#TAG:<Thing>` with
# angle brackets is the escape a document uses to SHOW the syntax without
# claiming the tag exists, and it is unmatched by TAG_REF for that reason.
TAG_REF = re.compile(re.escape(TAG) + r"(" + TAG_VALUE.pattern + r")")

GIST = 62
"""Hard cut for a tier-1 gist. Tier 1 is a gist or it is not tier 1."""


