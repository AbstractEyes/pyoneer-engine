def assign_tags(modules: list[Module]) -> None:
    """Give every module and entry its tag value, in place.

    THE RULE, and it is one sentence: a tag is the thing's own bare name,
    qualified by its module stem only when two things in the tree share that
    name. Bare by default is not laziness -- an agent looking up `GameEntity`
    knows the class name and does not yet know the module, so a scheme that
    demanded `game_entity.GameEntity` would demand the answer as the question.

    A method is always `Owner.name`: a bare `update` is claimed by 18 classes
    here and a tag that returns 18 lines is not an address. A property's setter
    takes `Owner.name.setter`, read straight off its own `@name.setter`
    decorator -- a getter and its setter are two definitions of one attribute,
    and naming them alike would make the single most common shape in this tree
    (30 pairs) the single most common tag collision.
    """
    claims: dict[str, int] = {}
    for module in modules:
        for entry in module.entries:
            if entry.kind != "method":
                claims[entry.name] = claims.get(entry.name, 0) + 1

    def qualify(module: Module, name: str) -> str:
        if claims.get(name, 0) < 2:
            return name
        stem = os.path.basename(module.relpath)[:-len(".py")]
        return "%s.%s" % (stem, name)

    for module in modules:
        module.tag = module.relpath                 # unique by construction
        owners: dict[str, str] = {}
        for entry in module.entries:
            if entry.kind == "class":
                entry.tag = qualify(module, entry.name)
                owners[entry.name] = entry.tag
            elif entry.kind in ("def", "const"):
                entry.tag = qualify(module, entry.name)
        for entry in module.entries:
            if entry.kind != "method":
                continue
            accessor = ""
            for dec in entry.decorators:
                head, _, kind = dec.partition(".")
                if head == entry.name and kind in ("setter", "getter", "deleter"):
                    accessor = "." + kind
            entry.tag = "%s.%s%s" % (owners.get(entry.owner, entry.owner),
                                     entry.name, accessor)

    # Anything still doubled -- a stem collision (two `errors.py`, two
    # `input.py`, sixteen `__init__.py`) or a name genuinely defined twice in
    # one scope -- is resolved deterministically rather than silently
    # deduplicated. A tag resolving to two places is the ONE failure this whole
    # scheme exists to prevent, so the resolution is total: qualify by the
    # dotted module, and if that is still not enough, number the repeats in
    # source order.
    def resolve(pick) -> None:
        groups: dict[str, list[Entry]] = {}
        for module in modules:
            for entry in module.entries:
                groups.setdefault(entry.tag, []).append(entry)
        for tag, entries in groups.items():
            if len(entries) < 2:
                continue
            for index, entry in enumerate(entries):
                entry.tag = pick(entry, index)

    dotted_of = {m.relpath: m.dotted for m in modules}

    def by_module(entry: Entry, index: int) -> str:
        # Rebuilt from the entry's own parts, never from the stem-qualified tag
        # it already carries -- `dotted + tag` would spell the stem twice.
        stem = os.path.basename(entry.relpath)[:-len(".py")]
        bare = entry.tag[len(stem) + 1:] if entry.tag.startswith(stem + ".") \
            else entry.tag
        return "%s.%s" % (dotted_of[entry.relpath], bare)

    def by_order(entry: Entry, index: int) -> str:
        return entry.tag if index == 0 else "%s.%d" % (entry.tag, index + 1)

    resolve(by_module)
    resolve(by_order)


@dataclass(frozen=True)
class TagSite:
    """Where a tag points, and how much of the file it speaks for."""
    tag: str
    kind: str
    name: str
    relpath: str
    lineno: int
    end_lineno: int

    @property
    def address(self) -> str:
        return "%s:%d" % (self.relpath, self.lineno)


def tag_index(modules: list[Module] | None = None) -> dict[str, TagSite]:
    """tag -> the one place it points. Every module, entry and constant."""
    modules = load() if modules is None else modules
    index: dict[str, TagSite] = {}
    for module in modules:
        index[module.tag] = TagSite(module.tag, "module", module.relpath,
                                    module.relpath, 1, module.lines)
        for entry in module.entries:
            index[entry.tag] = TagSite(entry.tag, entry.kind, entry.name,
                                       entry.relpath, entry.lineno,
                                       entry.end_lineno)
    return index


_CACHE: list[Module] | None = None


def load(refresh: bool = False) -> list[Module]:
    """Every mapped module, parsed and tagged. Cached: the walk is not free."""
    global _CACHE
    if _CACHE is None or refresh:
        modules = [parse_module(rel) for rel in source_files()]
        assign_tags(modules)
        _CACHE = modules
    return _CACHE


# ---------------------------------------------------------------------------
# Source-side tags: a `#TAG:` comment an author placed at a site by hand
# ---------------------------------------------------------------------------

def source_tags() -> list[tuple[str, str, int, str]]:
    """(tag, relpath, lineno, the whole line) for every `#TAG:` in the tree.

    These are the hand-placed ones -- the stable address a document uses when
    it needs to quote a line that is not itself a definition. The generated
    tags need no comment in the source; this is the escape hatch for the rest,
    and it is why `CLAUDE.md` can pin a sentence inside a docstring without
    naming a line number.
    """
    found: list[tuple[str, str, int, str]] = []
    for rel in source_files():
        text = read_source(rel)
        if TAG not in text:
            continue
        for number, line in enumerate(text.split("\n"), 1):
            for match in TAG_REF.finditer(line):
                found.append((match.group(1), rel, number, line))
    return found


