def expected() -> dict[str, str]:
    """Every file this generator owns -> exactly what it should contain."""
    modules = load()
    out = {INDEX_REL: render_index(modules)}
    for module in modules:
        out[tier2_rel(module)] = render_module(module)
    return out


def on_disk_tier2() -> list[str]:
    directory = os.path.join(ROOT, TIER2_DIR.replace("/", os.sep))
    if not os.path.isdir(directory):
        return []
    return sorted("%s/%s" % (TIER2_DIR, name)
                  for name in os.listdir(directory) if name.endswith(".md"))


def write_all() -> tuple[int, int]:
    """Write every generated file; delete tier-2 files with no module.

    Deleting is half the job. A map file left behind by a deleted module is
    exactly the failure this generator exists to prevent, and it is the one a
    writer never notices.
    """
    want = expected()
    directory = os.path.join(ROOT, TIER2_DIR.replace("/", os.sep))
    os.makedirs(directory, exist_ok=True)
    for rel, body in want.items():
        path = os.path.join(ROOT, rel.replace("/", os.sep))
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(body)
    removed = 0
    for rel in on_disk_tier2():
        if rel not in want:
            os.remove(os.path.join(ROOT, rel.replace("/", os.sep)))
            removed += 1
    return len(want), removed


def drift() -> list[str]:
    """Human-readable reasons the files on disk are not what they should be."""
    want = expected()
    problems: list[str] = []
    for rel, body in want.items():
        path = os.path.join(ROOT, rel.replace("/", os.sep))
        if not os.path.isfile(path):
            problems.append("%s is missing" % rel)
            continue
        with open(path, encoding="utf-8", newline="") as handle:
            found = handle.read().replace("\r\n", "\n")
        if found != body:
            a, b = found.split("\n"), body.split("\n")
            where = next((i for i in range(max(len(a), len(b)))
                          if a[i:i + 1] != b[i:i + 1]), 0)
            problems.append("%s differs at line %d: on disk %r, should be %r"
                            % (rel, where + 1,
                               (a[where:where + 1] or ["<eof>"])[0][:70],
                               (b[where:where + 1] or ["<eof>"])[0][:70]))
    for rel in on_disk_tier2():
        if rel not in want:
            problems.append("%s maps a module that no longer exists" % rel)
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--write", action="store_true",
                        help="regenerate docs/MAP.md and docs/map/*.md")
    parser.add_argument("--tags", action="store_true",
                        help="print the tag index and exit")
    args = parser.parse_args(argv)

    if args.tags:
        for tag, site in sorted(tag_index().items()):
            print("%-52s %-8s %s" % (TAG + tag, site.kind, site.address))
        return 0
    if args.write:
        written, removed = write_all()
        print("wrote %d file(s) (%s + %d tier-2)"
              % (written, INDEX_REL, written - 1))
        if removed:
            print("removed %d orphaned tier-2 file(s)" % removed)
        return 0

    problems = drift()
    for problem in problems:
        print("  DRIFT " + problem)
    if problems:
        print("\n%d problem(s). Regenerate:\n    %s"
              % (len(problems), REGENERATE))
        return 1
    modules = load()
    print("map is current: %d modules, %d tags"
          % (len(modules), len(tag_index(modules))))
    return 0


