@dataclass
class Entry:
    """One addressable thing: a class, a function, a method or a constant."""
    kind: str                       # "class" | "def" | "method" | "const"
    name: str
    relpath: str
    lineno: int
    end_lineno: int
    signature: str = ""             # "" for a constant
    returns: str = ""               # "" when undeclared
    doc: str = ""                   # first docstring line, "" when none
    owner: str = ""                 # the class, for a method
    bases: tuple[str, ...] = ()
    decorators: tuple[str, ...] = ()
    tag: str = ""                   # filled by `assign_tags`

    @property
    def public(self) -> bool:
        return not self.name.startswith("_")


@dataclass
class Module:
    relpath: str
    dotted: str
    doc: str = ""
    lines: int = 0
    imports: tuple[str, ...] = ()   # first-party only
    entries: list[Entry] = field(default_factory=list)
    tag: str = ""

    @property
    def package(self) -> str:
        head = os.path.dirname(self.relpath)
        return head or "."

    @property
    def classes(self) -> list[Entry]:
        return [e for e in self.entries if e.kind == "class"]

    @property
    def functions(self) -> list[Entry]:
        return [e for e in self.entries if e.kind == "def"]

    @property
    def constants(self) -> list[Entry]:
        return [e for e in self.entries if e.kind == "const"]

    def methods_of(self, owner: str) -> list[Entry]:
        return [e for e in self.entries if e.kind == "method" and e.owner == owner]


def _first_line(node) -> str:
    """The docstring's first LINE, squeezed. Never a paragraph.

    A tier-1 entry that carries a paragraph is a tier-2 entry in the wrong
    file, and this repository's whole complaint about documentation is that it
    grows until nobody reads it.
    """
    text = ast.get_docstring(node, clean=True) or ""
    for raw in text.split("\n"):
        line = " ".join(raw.split())
        if line:
            return line
    return ""


def _decorators(node) -> tuple[str, ...]:
    out = []
    for dec in node.decorator_list:
        try:
            out.append(ast.unparse(dec))
        except Exception:                                    # pragma: no cover
            out.append("?")
    return tuple(out)


def _signature(node) -> tuple[str, str]:
    """(args rendered with defaults, return annotation or "")."""
    try:
        args = ast.unparse(node.args)
    except Exception:                                        # pragma: no cover
        args = "..."
    returns = ""
    if node.returns is not None:
        try:
            returns = ast.unparse(node.returns)
        except Exception:                                    # pragma: no cover
            returns = "?"
    return args, returns


def _const_names(node) -> list[str]:
    """Module-level PUBLIC UPPER_CASE assignment targets.

    Upper case only, and that is a judgement the tree earns: a lower-case
    module-level assignment here is a cached singleton or a re-export, while
    the UPPER ones are the file-format strings, the registries and the bit
    masks -- exactly the things a document quotes and therefore exactly the
    things that need an address.
    """
    names = []
    if isinstance(node, ast.Assign):
        names = [t.id for t in node.targets if isinstance(t, ast.Name)]
    elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
        names = [node.target.id]
    return [n for n in names if n.isupper() and not n.startswith("_")]


def _first_party(tree: ast.Module) -> tuple[str, ...]:
    """Dotted first-party module names this module imports.

    Only the repository's own packages. Third-party noise (`pygame`, `PySide6`)
    is uniform and says nothing; a first-party import list is the one thing
    that makes law 2 -- `scripts/` may never import `editor/` -- auditable
    from a document instead of from a grep.
    """
    heads = set(ROOTS) - {"main.py"} | {"main"}
    found = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.split(".")[0] in heads:
                    found.add(alias.name)
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            if node.module.split(".")[0] in heads:
                found.add(node.module)
    return tuple(sorted(found))


def source_files() -> list[str]:
    """Every mapped `.py`, repo-relative with forward slashes, sorted."""
    found: list[str] = []
    for root in ROOTS:
        full = os.path.join(ROOT, root.replace("/", os.sep))
        if os.path.isfile(full):
            found.append(root)
            continue
        for dirpath, dirs, files in os.walk(full):
            dirs[:] = sorted(d for d in dirs if d != "__pycache__")
            for name in sorted(files):
                if name.endswith(".py"):
                    rel = os.path.relpath(os.path.join(dirpath, name), ROOT)
                    found.append(rel.replace(os.sep, "/"))
    return sorted(found)


def read_source(relpath: str) -> str:
    with open(os.path.join(ROOT, relpath.replace("/", os.sep)),
              encoding="utf-8", newline="") as handle:
        return handle.read().replace("\r\n", "\n")


def parse_module(relpath: str) -> Module:
    return parse_text(relpath, read_source(relpath))


def parse_text(relpath: str, text: str) -> Module:
    """The AST facts for one module, from TEXT rather than from disk.

    Split out from `parse_module` so a check can drive this generator over a
    fixture it wrote itself. Every rule here would otherwise be asserted only
    against the live tree -- and "the renderer prints the signature it read" is
    exactly the kind of claim that passes vacuously when the only thing that
    can prove it is the same tree it was read from.
    """
    dotted = relpath[:-len(".py")].replace("/", ".")
    module = Module(relpath=relpath, dotted=dotted,
                    lines=len(text.split("\n")))
    try:
        tree = ast.parse(text)
    except SyntaxError:                                      # pragma: no cover
        return module
    module.doc = _first_line(tree)
    module.imports = _first_party(tree)
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            bases = []
            for base in node.bases:
                try:
                    bases.append(ast.unparse(base))
                except Exception:                            # pragma: no cover
                    bases.append("?")
            module.entries.append(Entry(
                kind="class", name=node.name, relpath=relpath,
                lineno=node.lineno, end_lineno=node.end_lineno,
                doc=_first_line(node), bases=tuple(bases),
                decorators=_decorators(node)))
            for child in node.body:
                if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    args, returns = _signature(child)
                    module.entries.append(Entry(
                        kind="method", name=child.name, relpath=relpath,
                        lineno=child.lineno, end_lineno=child.end_lineno,
                        signature=args, returns=returns,
                        doc=_first_line(child), owner=node.name,
                        decorators=_decorators(child)))
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            args, returns = _signature(node)
            module.entries.append(Entry(
                kind="def", name=node.name, relpath=relpath,
                lineno=node.lineno, end_lineno=node.end_lineno,
                signature=args, returns=returns, doc=_first_line(node),
                decorators=_decorators(node)))
        else:
            for name in _const_names(node):
                module.entries.append(Entry(
                    kind="const", name=name, relpath=relpath,
                    lineno=node.lineno,
                    end_lineno=getattr(node, "end_lineno", node.lineno)))
    return module


