class _ProbeEntity(GameEntity):
    """A GameEntity that is constructible. Filling the two abstract methods
    is the whole difference between the base class and something a check can
    stand up, and it needs no art."""

    def core_lifecycle_build(self, event=None):
        pass

    def core_input_receive(self, events=None):
        pass


class _Spy(EntityBehavior):
    """Counts the frames the drive gave it."""

    def __init__(self):
        self.calls = 0

    def update(self, entity, event):
        self.calls += 1


_SPY_SPEC = BehaviorSpec(name="probe_spy",
                         summary="Counts update calls. Never registered.",
                         factory=_Spy, order=50)


def drive_calls(frames: int, enabled: bool = True,
                entity_class=None) -> int | None:
    """How many times a bound behavior's `update` ran over `frames` frames.

    None when there is no `EntityBehaviors` on the entity to attach to at all,
    which is a different answer from zero: nothing to drive versus a drive
    that does not run.

    A COUNT rather than a boolean, and driven for a caller-chosen number of
    frames, because the two ways this wire breaks look identical to a
    single-frame yes/no probe: a drive that fires once at attach and never
    again returns 1 for any frame count, and a drive that fires twice per
    frame returns 2 for one frame. Only `calls == frames` for more than one
    value of `frames` separates them from a working one.

    `entity_class` is section 9's seam: an entity with no holder, a holder of
    the wrong type, a dead drive and a doubled one are all constructible from
    out here, so rows 1 and 2 are watched saying `no` without the engine being
    edited to make them.
    """
    entity = (_ProbeEntity if entity_class is None else entity_class)()
    holder = getattr(entity, HOLDER, None)
    if not isinstance(holder, EntityBehaviors):
        return None
    spy = _Spy()
    spy.spec = _SPY_SPEC
    holder.attach(spy)
    spy.enabled = enabled
    for _ in range(frames):
        entity.core_frame_update(PyoneerEvent(GameEventType.UPDATE,
                                              data={"delta": 1.0}))
    return spy.calls


def entity_drives_behaviors(entity_class=None) -> bool:
    """True when `GameEntity.core_frame_update` really runs a bound behavior."""
    return drive_calls(2, entity_class=entity_class) == 2


