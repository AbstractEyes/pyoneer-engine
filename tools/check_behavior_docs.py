# The rules. Every one is a pure function over (registry, packs, text) so it
# can be driven by a fixture that violates it and by the live tree, which
# must not.
# ===========================================================================

HEADING = re.compile(r"^### `([a-z][a-z0-9_]*)`$", re.M)
# The two tables both begin `| \`token\` | `, and telling them apart is the
# second cell: the summary table's is the integer run order, a parameter
# table's is a declared type. Matching on the token alone credited every
# parameter key as a behavior and made the catalogue assertion pass for a
# document that listed none of the right things.
SUMMARY_ROW = re.compile(r"^\| `([a-z][a-z0-9_]*)` \| \d+ \| ", re.M)
# Non-capturing on the type: `findall` returns a tuple per match the moment a
# pattern has two groups, and a list of tuples compared against a list of
# strings is never equal -- an assertion that fails for the wrong reason is
# only marginally better than one that cannot fail.
PARAM_ROW = re.compile(r"^\| `([a-z][a-z0-9_]*)` \| (?:int|float|str|bool) \| ",
                       re.M)
PYONEER_NAME = re.compile(r"\bpyoneer_[a-zA-Z0-9_]*")
GAME_CLASS = re.compile(r"\bGame[A-Z][A-Za-z0-9_]*")

WIDENS = {("float", "int")}
"""(parameter type, column type) pairs where the mismatch is deliberate.

`BehaviorParam.coerce` widens an int to a float, because Tiled writes `900`
for a float-typed property and calling that an authoring error would make
every whole-number float one. The reverse does NOT widen -- a float into an
int parameter raises -- so it is not symmetric and this set is not a pair of
sets.
"""


def catalogue_tokens(text: str) -> tuple[tuple[str, ...], tuple[str, ...]]:
    """(tokens with a section, tokens with a summary row) as the FILE has them.

    Two separate expressions render these in `describe_all`, so reading only
    one of them would let the other drift -- a behavior listed in the table
    and missing its section reads as documented right up until somebody
    scrolls.
    """
    return tuple(HEADING.findall(text)), tuple(SUMMARY_ROW.findall(text))


def documented_params(text: str) -> dict[str, tuple[str, ...]]:
    """behavior token -> the parameter keys its own section documents.

    Sliced by section rather than scanned whole: a parameter row belongs to
    the behavior whose heading precedes it, and a global scan would let a
    parameter documented under the wrong behavior pass.
    """
    found: dict[str, tuple[str, ...]] = {}
    marks = [(m.group(1), m.start()) for m in HEADING.finditer(text)]
    for index, (token, start) in enumerate(marks):
        end = marks[index + 1][1] if index + 1 < len(marks) else len(text)
        found[token] = tuple(PARAM_ROW.findall(text[start:end]))
    return found


def column_violations(registry, packs) -> list[str]:
    """Every actors column a behavior consumes that its genre does not declare.

    THE ASSERTION WITH TEETH. A behavior declaring
    `BehaviorParam("gravity", ..., source="actors")` is making a claim about
    the project's data model, and the claim is checkable: the pack it names in
    `genres` must have an `actors` table with a `gravity` column of a
    compatible type. Nothing else in the tree checks it -- nothing in
    `scripts/` reads `data/project/` at all, so the mismatch would surface as
    a parameter that silently took its default on every actor, forever.

    A `source="actors"` parameter on a behavior that declares NO genre is a
    violation too. `genres=()` means "any", and a column that any pack may or
    may not have is a column no pack is answerable for.
    """
    found: list[str] = []
    for spec in sorted(registry.values(), key=lambda s: s.name):
        actor_params = [p for p in spec.params if p.source == "actors"]
        if not actor_params:
            continue
        if not spec.genres:
            found.append(
                "behavior %r reads %s from the actors table but declares no "
                "genres, so no pack is answerable for the column(s). Add the "
                "genre id(s) to its BehaviorSpec."
                % (spec.name, ", ".join(repr(p.key) for p in actor_params)))
            continue
        for genre_id in spec.genres:
            pack = packs.get(genre_id)
            if pack is None:
                found.append(
                    "behavior %r declares genre %r, which is not a pack on "
                    "disk (%s)" % (spec.name, genre_id,
                                   ", ".join(sorted(packs)) or "none"))
                continue
            table = pack.table("actors")
            if table is None:
                found.append(
                    "behavior %r declares genre %r, whose pack has no 'actors' "
                    "table to read %s from"
                    % (spec.name, genre_id,
                       ", ".join(repr(p.key) for p in actor_params)))
                continue
            for param in actor_params:
                column = table.field(param.key)
                if column is None:
                    found.append(
                        "behavior %r consumes actors column %r, and genre %r "
                        "does not declare it. Add it to "
                        "editor/genres/%s/genre.json, or change the parameter "
                        "to source=\"object\"."
                        % (spec.name, param.key, genre_id, genre_id))
                elif (column.type != param.type
                      and (param.type, column.type) not in WIDENS):
                    found.append(
                        "behavior %r declares %r as %s and genre %r declares "
                        "that column as %s; an authored value would be refused "
                        "by BehaviorParam.coerce"
                        % (spec.name, param.key, param.type, genre_id,
                           column.type))
    return found


def spawn_violations(packs, registry=None) -> list[str]:
    """Every object class a pack allows that the spawn registry cannot build.

    `spawn_objects` RAISES on an unknown Type, so an object placed from a
    class the pack advertised makes the whole map unloadable -- and the editor
    validates placements against exactly this list, so the pack advertising a
    class the engine cannot build is the editor telling an author to break
    their map.
    """
    table = SPAWN_REGISTRY if registry is None else registry
    found: list[str] = []
    for pack in sorted(packs.values(), key=lambda p: p.id):
        for layer in pack.layers:
            for kind in layer.object_types:
                if kind not in table:
                    found.append(
                        "genre %r allows object class %r on layer %r, and it "
                        "is not in SPAWN_REGISTRY (%s), so an object of that "
                        "Type makes the map raise at load"
                        % (pack.id, kind, layer.name,
                           ", ".join(sorted(table)) or "empty"))
            for kind in layer.unique_types:
                if kind not in layer.object_types:
                    found.append(
                        "genre %r declares %r unique on layer %r without "
                        "allowing it there" % (pack.id, kind, layer.name))
    return found


def default_list_violations(raw_packs, registry) -> list[str]:
    """Every behavior token a pack declares as a class default that is unknown.

    The slot is `layers[].object_classes[] = {"type": ..., "behaviors": [...]}`
    and NO pack fills it today, deliberately: the registry is empty, so a
    declared default would name a token that raises. The rule is written now
    anyway, because the day a pack fills it is the day it needs checking, and
    a rule added afterwards checks nothing that already shipped.
    """
    found: list[str] = []
    for genre_id in sorted(raw_packs):
        raw = raw_packs[genre_id]
        for layer in raw.get("layers", []):
            allowed = list(layer.get("object_types", []))
            for entry in layer.get("object_classes", []):
                kind = entry.get("type", "")
                if allowed and kind not in allowed:
                    found.append(
                        "genre %r declares default behaviors for object class "
                        "%r on layer %r, which that layer does not allow"
                        % (genre_id, kind, layer.get("name", "?")))
                for token in parse_list(entry.get("behaviors", [])):
                    if token not in registry:
                        found.append(
                            "genre %r gives object class %r the default "
                            "behavior %r, which is not registered (%s)"
                            % (genre_id, kind, token,
                               ", ".join(sorted(registry)) or "the registry "
                               "is empty"))
    return found


def vocabulary_violations(text: str, where: str, registry=None) -> list[str]:
    """Every `pyoneer_*` name in `text` that is not a real property name.

    This is the spelling guard extended to the prose. A property written into
    a .tmx under a name nothing reads does nothing at all and reports nothing,
    and this repository has already lost 39 authored tiles to exactly that --
    so a document that teaches `pyoneer_behaviours` (the British form, which
    the vocabulary does not use) is a document that teaches an author to write
    a dead property.
    """
    table = BEHAVIOR_REGISTRY if registry is None else registry
    known = set(layer_profile.KNOWN) | {BEHAVIORS, ACTOR}
    # The two bare prefixes are legal prose -- "the `pyoneer_` prefix is
    # load-bearing", "a stray `pyoneer_param_` nothing consumes" -- and are
    # not claims that a property by that name exists.
    prefixes = {layer_profile.PREFIX, PARAM_PREFIX}
    found: list[str] = []
    for name in sorted(set(PYONEER_NAME.findall(text))):
        if name in known or name in prefixes:
            continue
        if name.startswith(PARAM_PREFIX):
            suffix = name[len(PARAM_PREFIX):]
            if TOKEN.match(suffix):
                continue
            found.append(
                "%s writes %r, whose parameter key %r is not snake_case"
                % (where, name, suffix))
            continue
        found.append(
            "%s writes the property name %r, which is not one the engine "
            "reads. Known: %s, and %s<key>."
            % (where, name, ", ".join(sorted(known)), PARAM_PREFIX))
    return found


def rules_coverage_violations(text: str, genre_id: str, registry) -> list[str]:
    """Behaviors that claim this genre and are not named in its RULES.md.

    Only the genre-EXCLUSIVE ones. A behavior declaring `genres=()` applies
    everywhere and lives in the generated document; requiring every pack to
    restate the whole catalogue would rebuild in prose the thing that
    generation exists to stop. But a behavior that says *I am the platformer's
    body* and goes unmentioned in the platformer's rules is a behavior an AI
    reading that pack will not know to reach for -- which is the same failure
    as it not existing.
    """
    found: list[str] = []
    for spec in sorted(registry.values(), key=lambda s: s.name):
        if genre_id not in spec.genres:
            continue
        if ("`%s`" % spec.name) not in text:
            found.append(
                "behavior %r declares genre %r and %s/RULES.md never names it, "
                "so nothing reading that pack learns it exists"
                % (spec.name, genre_id, genre_id))
    return found


def missing_class_names(text: str, defined: set[str]) -> list[str]:
    """Every `Game*` class the text names that is not defined anywhere.

    A rules document that teaches a class name the tree does not have sends
    an AI to grep for it, find nothing, and invent one -- which is how a
    genre pack ends up prescribing a subclass in the same breath as telling
    you not to write subclasses.
    """
    return sorted({name for name in GAME_CLASS.findall(text)
                   if name not in defined})


def defined_names() -> set[str]:
    """Every class and function name defined under scripts/, editor/, config/.

    AST, not grep: a name in a docstring or a comment is not a definition, and
    counting one would make this rule pass for a class that only exists in
    prose -- which is the exact failure it is written to catch.
    """
    names: set[str] = set()
    roots = [os.path.join(ROOT, part) for part in ("scripts", "editor", "config")]
    roots.append(os.path.join(ROOT, "main.py"))
    for root in roots:
        walk = ([(os.path.dirname(root), [], [os.path.basename(root)])]
                if os.path.isfile(root) else os.walk(root))
        for dirpath, _dirs, files in walk:
            if "__pycache__" in dirpath:
                continue
            for name in files:
                if not name.endswith(".py"):
                    continue
                with open(os.path.join(dirpath, name), encoding="utf-8") as handle:
                    try:
                        tree = ast.parse(handle.read())
                    except SyntaxError:
                        continue
                for node in ast.walk(tree):
                    if isinstance(node, (ast.ClassDef, ast.FunctionDef)):
                        names.add(node.name)
    return names


