def _genre_section(packs) -> list[str]:
    lines = ["## What each genre pack declares", "",
             "Derived from `editor/genres/*/genre.json`, so a pack that gains "
             "a column gains it here. A behavior whose parameter declares "
             "`source=\"actors\"` may name any column in its genre's table "
             "below -- and only those, which is what this check enforces.", ""]
    for genre_id in sorted(packs):
        pack = packs[genre_id]
        lines.append("### `%s` -- %s" % (genre_id, pack.title))
        lines.append("")
        gated = [l.name for l in pack.layers if l.collision]
        lines.append("- **passability is authored against** %s"
                     % (", ".join("`%s` (companion `%sCollision`)" % (n, n)
                                  for n in gated) or "no layer"))
        for layer in pack.layers:
            if layer.kind != "object":
                continue
            lines.append("- **object layer `%s` allows** %s"
                         % (layer.name,
                            ", ".join("`%s`" % t for t in layer.object_types)
                            or "nothing"))
        actors = pack.table("actors")
        if actors is None:
            lines.append("- **no `actors` table**, so no `source=\"actors\"` "
                         "parameter can resolve here")
        else:
            lines.append("- **actors columns a parameter may name** %s"
                         % ", ".join("`%s` (%s)" % (f.name, f.type)
                                     for f in actors.fields))
        defaults = []
        for layer in pack.layers:
            for declared in layer.object_classes:
                defaults.append("`%s` on `%s` -> `%s`"
                                % (declared.type, layer.name,
                                   declared.behaviors_text or "nothing"))
        if defaults:
            lines.append(
                "- **default behavior lists** %s. The editor MATERIALISES "
                "these into the object's `%s` property when the object is "
                "added, so the `.tmx` stays the whole truth and the engine "
                "never has to read a pack -- `scripts/` may not import "
                "`editor/`. It is a STARTING VALUE, not a policy: edit the "
                "list on the object afterwards and your edit stands, because "
                "nothing reads the pack again."
                % (", ".join(defaults), BEHAVIORS))
        else:
            lines.append(
                "- **default behavior lists** none declared. The pack may "
                "declare them as `layers[].object_classes[].behaviors`; the "
                "editor MATERIALISES such a default into the object when the "
                "object is added, so the `.tmx` stays the whole truth and the "
                "engine never has to read a pack -- `scripts/` may not import "
                "`editor/`.")
        lines.append("")
    return lines


def _swap_section(registry) -> list[str]:
    lines = ["## Swapping one behavior list for another", "",
             "This is the whole point of the design: the same class, the same "
             "spawn entry, a different list.", ""]
    if not registry:
        lines.append(
            "There is nothing to swap yet -- the registry is empty, so every "
            "token below would raise `PyoneerAssetMissingError`. The shape it "
            "will take, with the tokens left as placeholders on purpose:")
        lines.append("")
        lines.append("```xml")
        lines.append('<object id="1" type="GamePlayer" x="64" y="96">')
        lines.append("  <properties>")
        lines.append('    <property name="%s" value="&lt;move&gt;,&lt;collide&gt;"/>'
                     % BEHAVIORS)
        lines.append('    <property name="%smove_speed" type="int" value="24"/>'
                     % PARAM_PREFIX)
        lines.append("  </properties>")
        lines.append("</object>")
        lines.append("```")
        lines.append("")
        lines.append(
            "Change the value of `%s` and the object plays differently with "
            "no code change and no new class. Nothing else about the object "
            "moves: same `type`, same `SPAWN_REGISTRY` entry, same depth."
            % BEHAVIORS)
        lines.append("")
        return lines
    ordered = sorted(registry.values(), key=lambda s: (s.order, s.name))
    neutral = [s.name for s in ordered if not s.genres]
    claimed = sorted({g for s in ordered for g in s.genres})
    lines.append("| genre | a complete, legal list |")
    lines.append("| --- | --- |")
    for genre_id in claimed:
        chosen: list[str] = []
        for spec in ordered:
            if spec.genres and genre_id not in spec.genres:
                continue
            # This column is read as a RECOMMENDATION, so it may only offer
            # what works out of the box. A `needs-host` behavior runs
            # correctly and still does nothing until the game assigns
            # something the engine never will -- and `requires` is reported,
            # never enforced, so there is no crash to reveal the mistake.
            # `authoring-only` is excluded for the plainer reason.
            if spec.status != "live":
                continue
            # Legality is decided by the engine's own rule, not by a second
            # copy of it here: a candidate is accepted only if `validate_list`
            # accepts the list it would produce. That is what keeps this table
            # from ever printing a pair the loader would refuse.
            try:
                validate_list(chosen + [spec.name], registry)
            except Exception:                              # declared conflict
                continue
            chosen.append(spec.name)
        lines.append("| `%s` | `%s` |" % (genre_id, format_list(chosen)))
    lines.append("")
    lines.append("Set the object's `%s` property to one of those values. Same "
                 "`type`, same `SPAWN_REGISTRY` entry, same depth, same class "
                 "-- only the list changes. %s"
                 % (BEHAVIORS,
                    ("%s declare no genre and so belong in any list."
                     % ", ".join("`%s`" % n for n in neutral))
                    if neutral else ""))
    lines.append("")
    return lines


def render_doc(registry=None, packs=None) -> str:
    """The whole of `docs/BEHAVIORS.md`, from the registry and the packs.

    `describe_all()` first and verbatim, so the half the engine owns is not
    paraphrased anywhere. Then the two things it cannot see: what the engine
    around it has wired, and what the packs declare.
    """
    registry = BEHAVIOR_REGISTRY if registry is None else registry
    if packs is None:
        packs = load_packs()
    lines = [describe_all(registry).rstrip("\n"), "", SENTINEL, ""]
    lines.append("## Integration status")
    lines.append("")
    rows = integration_rows()
    lines.append(WIRED if all(ok for _, ok, _ in rows[:2]) else UNWIRED)
    lines.append("")
    lines.append(
        "Every row below is measured, not declared: the drive row is produced "
        "by constructing a real `GameEntity`, attaching a behavior and running "
        "two frames. A row that says *no* is a wire that does not exist, not a "
        "wire that is merely undocumented.")
    lines.append("")
    lines.append("| the wire | at this commit | what it takes |")
    lines.append("| --- | --- | --- |")
    for what, ok, cost in rows:
        lines.append("| %s | %s | %s |" % (what, "**yes**" if ok else "no", cost))
    lines.append("")
    lines.extend(_genre_section(packs))
    lines.extend(_swap_section(registry))
    return "\n".join(lines).rstrip("\n") + "\n"


def load_packs():
    """id -> GenrePack, for every pack on disk.

    The loaded pack only, never the raw `genre.json` beside it: a file format
    with two readers in one process is the shape that lets a rule and its
    subject disagree.
    """
    return {genre_id: genre_module.load(genre_id)
            for genre_id in genre_module.available()}


