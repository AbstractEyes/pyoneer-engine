failures: list[str] = []
asserted: list[str] = []


def expect(label, got, want):
    asserted.append(label)
    ok = got == want
    print(f"  {'ok  ' if ok else 'FAIL'} {label:<62} got={got!r} want={want!r}")
    if not ok:
        failures.append(label)


def expect_true(label, got):
    asserted.append(label)
    ok = bool(got)
    print(f"  {'ok  ' if ok else 'FAIL'} {label:<62} got={got!r}")
    if not ok:
        failures.append(label)


def expect_reports(label, violations, *fragments):
    """Exactly one violation, and it must name every fragment.

    The fragments are the teeth. `len(violations) == 1` passes for a
    violation raised by the wrong rule about the wrong thing, and this check
    exists precisely to distinguish "the column is missing" from "the pack is
    missing" -- two rules that share a code path and would otherwise cover
    for each other.
    """
    asserted.append(label)
    if len(violations) != 1:
        print(f"  FAIL {label:<62} {len(violations)} violation(s): {violations}")
        failures.append(label)
        return
    text = violations[0]
    missing = [f for f in fragments if f not in text]
    ok = not missing
    print(f"  {'ok  ' if ok else 'FAIL'} {label:<62} {text[:70]}")
    if not ok:
        failures.append(f"{label} (message lacks {missing})")


