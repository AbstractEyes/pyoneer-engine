"""Verify the behavior system's DOCUMENTATION cannot drift from the system.

    .venv/Scripts/python.exe tools/check_behavior_docs.py
    .venv/Scripts/python.exe tools/check_behavior_docs.py --write   # regenerate

`tools/check_behavior.py` proves the machinery works. This file proves the
paper agrees with the machinery, which is a separate failure and a worse one:
a broken behavior raises on the first frame, while a document that describes a
behavior the engine cannot run sends an AI to write a `.tmx` that raises at
load, and a document that omits one the engine CAN run means the behavior is
never used at all.

WHAT IS ASSERTED
----------------
     1. `docs/BEHAVIORS.md` is exactly what the generator produces, and its
        first half is byte-for-byte `registry.describe_all()`
     2. the catalogue in the FILE names exactly the registered behaviors,
        in both of the two places it names them
     3. every parameter the file documents is one its behavior declares
     4. every actors column a behavior consumes is declared by the genre
        pack that behavior claims  <- the one with teeth
     5. a pack's `object_types` are all spawnable, so an authored object
        cannot make the map raise at load
     6. every `pyoneer_*` property name printed in the docs or in either
        RULES.md is a real vocabulary constant, correctly spelled
     7. both RULES.md files point at the generated document, do not claim a
        behavior exists while the registry is empty, and name no `Game*`
        class that is absent from the tree
     8. the integration status written in the file matches what the code
        actually does when driven
     9. EVERY column of that integration table goes `no` when the code it
        describes is broken  <- the negative corpus

THE ONE TABLE `CLAUDE.md` TELLS EVERY READER TO TRUST
-----------------------------------------------------
`CLAUDE.md` routes readers here with the instruction to trust this document's
MEASURED integration table over any prose, including its own preamble. That
makes a detector reporting a wire which is not there the most expensive kind
of wrong available in this tree -- and the sibling instrument one file over,
`tools/check_event_docs.py`, was caught printing `yes` over broken code in
three consecutive passes.

Two of the detectors behind this table had the same two shapes. `_calls`
matched a bare `func.id`/`func.attr` with no resolution through the import
that brought the name in, so any function with a matching NAME satisfied it;
`_assigns_collision_field` was a regex over source text, which counted a
comment, a docstring and an `==`. Neither had ever been watched saying `no`.
Section 9 is the repair the sibling already carries: `ROW_KEYS` + `CORPUS`, a
gate that every row is claimed by exactly one key, and a per-row gate that it
is driven BOTH ways. Nothing in it edits a tracked file.

THE DOCUMENT IS GENERATED, INCLUDING THE PARTS THAT ARE NOT `describe_all`
-------------------------------------------------------------------------
`describe_all()` renders the registry. `render_doc()` below renders the
registry AND the two things the registry cannot see: what the surrounding
engine has actually wired up, and what each genre pack declares. Both halves
are derived -- the integration table is produced by DRIVING a real
`GameEntity`, not by reading a flag someone remembered to set -- so the whole
file is regenerated by one command and the check is an equality.

THE FIXTURES ARE THIS FILE'S OWN
--------------------------------
A rule run only over the live tree passes whenever the live tree happens to be
clean, and passes vacuously whenever it iterates nothing. So each rule below
is driven twice: once against a hand-built fixture registry and fixture genre
pack that is KNOWN to violate it, and once against the live registry and the
real packs, which must be clean. `data/maps/starter.tmx` is never read.
"""
